#!/usr/bin/env node
/**
 * build-icons.mjs
 * Reads every sanitized svg in packages/react/src/icons/svg/ and generates
 * packages/react/src/icons/index.tsx: one createIcon() component per icon
 * plus an iconRegistry map. Run after scripts/sanitize-icons.mjs.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SVG_DIR = join(ROOT, 'packages/react/src/icons/svg');
const OUT_FILE = join(ROOT, 'packages/react/src/icons/index.tsx');

function getAttr(tag, name) {
  const m = tag.match(new RegExp(`${name}="([^"]*)"`));
  return m ? m[1] : null;
}

/** Escape a string for inclusion in a single-quoted JS literal. */
function jsString(s) {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const files = readdirSync(SVG_DIR)
  .filter((f) => f.endsWith('.svg'))
  .sort((a, b) => a.localeCompare(b));

const components = [];
const registry = [];

for (const file of files) {
  const name = basename(file, '.svg');
  const raw = readFileSync(join(SVG_DIR, file), 'utf8').trim();
  const rootTag = raw.match(/<svg\b[^>]*>/);
  if (!rootTag) {
    console.warn(`skip ${file}: no <svg> root`);
    continue;
  }
  const viewBox = getAttr(rootTag[0], 'viewBox');
  const fill = getAttr(rootTag[0], 'fill') ?? 'none';
  if (!viewBox) {
    console.warn(`skip ${file}: no viewBox`);
    continue;
  }
  const inner = raw
    .slice(raw.indexOf(rootTag[0]) + rootTag[0].length, raw.lastIndexOf('</svg>'))
    .trim();

  const fillArg = fill === 'none' ? '' : `, ${jsString(fill)}`;
  components.push(
    `export const ${name}Icon = createIcon(${jsString(viewBox)}, ${jsString(inner)}${fillArg});`
  );
  registry.push(`  ${name}: ${name}Icon,`);
}

const out = `// Generated by scripts/build-icons.mjs from Figma node 2092:127 — do not edit by hand.
// Source svgs: packages/react/src/icons/svg/ (sanitized by scripts/sanitize-icons.mjs).
import type { ComponentType } from 'react';
import { createIcon, type IconProps } from './createIcon';

export type { IconProps } from './createIcon';
export { createIcon } from './createIcon';

${components.join('\n')}

export const iconRegistry = {
${registry.join('\n')}
} satisfies Record<string, ComponentType<IconProps>>;

export type IconName = keyof typeof iconRegistry;
`;

writeFileSync(OUT_FILE, out);
console.log(`Generated ${OUT_FILE} with ${components.length} icon components.`);
