/**
 * Lepidus CSS build — Style Dictionary v4 over DTCG sources.
 *
 * Sources (W3C DTCG, reference-bound) live in src/:
 *   primitive.tokens.json · semantic.light/dark/hc.tokens.json · component.tokens.json
 *
 * Emits packages/tokens/build/css/tokens.css with the Primitive → Semantic →
 * Component chain preserved as var() references (outputReferences) and theming
 * via [data-theme]:
 *   :root                  primitives + semantic(light) + component
 *   [data-theme="dark"]    semantic overrides
 *   [data-theme="hc"]      semantic overrides (high contrast)
 *
 * CSS variable names come from each token's Figma Dev-Mode code syntax
 * (com.figma.codeSyntax.WEB), so code and Figma stay in lock-step.
 *
 * Run: node packages/tokens/build-sd.mjs   (npm run tokens:css)
 */
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = join(__dirname, 'src');
const OUTDIR = join(__dirname, 'build', 'css');
const s = (f) => join(SRC, f);

// --- name transform: use the exact Figma Dev-Mode variable name -------------
const codeSyntaxName = (token) => {
  const web =
    token.$extensions?.['com.figma.codeSyntax']?.WEB ??
    token.original?.$extensions?.['com.figma.codeSyntax']?.WEB;
  if (web) return web.replace(/^var\(\s*--/, '').replace(/\s*\)\s*$/, '');
  return token.path.join('-');
};

StyleDictionary.registerTransform({
  name: 'name/figmaCodeSyntax',
  type: 'name',
  transform: codeSyntaxName,
});

// Names from Figma code syntax; color normalised to CSS. Dimensions are already
// authored as "px" strings and fontWeights as numbers, so they pass through.
const TRANSFORMS = ['name/figmaCodeSyntax', 'color/css'];

/** Build one CSS layer to a temp file and return its body (declarations only). */
async function buildLayer({ label, sources, selector, dest, filter }) {
  const sd = new StyleDictionary({
    source: sources,
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transforms: TRANSFORMS,
        buildPath: OUTDIR + '/',
        options: { outputReferences: true },
        files: [
          {
            destination: dest,
            format: 'css/variables',
            filter,
            options: { selector, showFileHeader: false },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
  const full = join(OUTDIR, dest);
  const body = readFileSync(full, 'utf8').trim();
  rmSync(full);
  return `/* ${label} */\n${body}`;
}

const onlyFrom = (file) => (token) => token.filePath.endsWith(file);

const layers = [
  await buildLayer({
    label: 'PRIMITIVES + SEMANTIC (Light) + COMPONENT',
    // base.tokens.json = hand-authored primitives the Figma export lacks (e.g. font family)
    sources: [
      s('base.tokens.json'),
      s('primitive.tokens.json'),
      s('semantic.light.tokens.json'),
      s('component.tokens.json'),
    ],
    selector: ':root',
    dest: '_base.css',
  }),
  await buildLayer({
    label: 'SEMANTIC — Dark',
    sources: [s('primitive.tokens.json'), s('semantic.dark.tokens.json')],
    selector: '[data-theme="dark"]',
    dest: '_dark.css',
    filter: onlyFrom('semantic.dark.tokens.json'),
  }),
  await buildLayer({
    label: 'SEMANTIC — High Contrast',
    sources: [s('primitive.tokens.json'), s('semantic.hc.tokens.json')],
    selector: '[data-theme="hc"]',
    dest: '_hc.css',
    filter: onlyFrom('semantic.hc.tokens.json'),
  }),
];

// Some Figma tokens at different tiers share one CSS variable name (e.g. the
// semantic `spacing.component.card.padding` and the component `card.padding`
// both map to --component-card-padding). With outputReferences the later
// (component) tier emits `--x: var(--x)`, a cyclic self-reference CSS treats as
// invalid. Drop those self-ref lines so the valid earlier declaration wins.
let selfRefs = 0;
const dropSelfRefs = (css) =>
  css
    .split('\n')
    .filter((line) => {
      const m = /^\s*(--[A-Za-z0-9-]+):\s*var\(\s*(--[A-Za-z0-9-]+)\s*\)\s*;\s*$/.exec(line);
      if (m && m[1] === m[2]) { selfRefs++; return false; }
      return true;
    })
    .join('\n');

const out = dropSelfRefs(
  [
    '/* ============================================',
    '   LEPIDUS DESIGN SYSTEM — GENERATED TOKENS',
    '   Built by Style Dictionary v4 from packages/tokens/src/*.tokens.json (DTCG)',
    '   Generated by packages/tokens/build-sd.mjs — DO NOT EDIT BY HAND',
    '   Primitive → Semantic → Component, themed via [data-theme]',
    '   ============================================ */',
    '',
    ...layers,
  ].join('\n') + '\n'
);

writeFileSync(join(OUTDIR, 'tokens.css'), out);
const count = out.match(/^\s+--/gm)?.length ?? 0;
console.log(`✓ Wrote ${join(OUTDIR, 'tokens.css')} (${count} declarations, 3 theme layers, ${selfRefs} self-refs dropped)`);
